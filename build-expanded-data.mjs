const ids = new Set();
for (const resource of resources) {
  if (ids.has(resource.id)) throw new Error(`Duplicate ID: ${resource.id}`);
  ids.add(resource.id);
  for (const field of requiredFields) {
    if (!(field in resource)) throw new Error(`Missing ${field} on ${resource.id}`);
  }
  if (!['basic', 'clinical', 'exams', 'reference'].includes(resource.category)) {
    throw new Error(`Invalid category on ${resource.id}`);
  }
  if (!Array.isArray(resource.sections) || !resource.sections.length) {
    throw new Error(`Missing sections on ${resource.id}`);
  }
  if (!/^https:\/\//.test(resource.link)) {
    throw new Error(`Non-HTTPS link on ${resource.id}`);
  }
}

