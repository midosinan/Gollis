  'primary-surgery-non-trauma': ['general-surgery', 'anatomical-surgery', 'faculty-of-medicine'],
  'who-pocket-book-children': ['pediatrics', 'faculty-of-medicine'],
  'who-intrapartum-care': ['obstetrics-gynecology', 'faculty-of-medicine'],
  'who-antenatal-care': ['obstetrics-gynecology', 'faculty-of-medicine'],
